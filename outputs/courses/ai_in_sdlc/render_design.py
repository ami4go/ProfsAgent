"""Renders runs/ai-in-sdlc-01/state.json as the readable course design (outputs/courses/ai_in_sdlc/COURSE_DESIGN.md)."""
import json
from pathlib import Path

st = json.load(open("D:/BTP/runs/ai-in-sdlc-01/state.json", encoding="utf-8"))
out = Path("D:/BTP/outputs/courses/ai_in_sdlc/COURSE_DESIGN.md")
c = st["cco_compact"]
tmap = {t["id"]: (t, m) for m in st["modules"] for t in m["topics"]}
week_of = {t: w[0] for t, w in st["schedule"]["topic_weeks"].items()}
L = []
a = L.append
a(f"# {c['course_name']}\n")
a(f"**Credits:** {st['credits']} · **L-T-P:** {st['ltp']['L']}-{st['ltp']['T']}-{st['ltp']['P']} (credits = L + T + P/2) · "
  f"**Weeks:** {st['weeks']} (mid-semester exam after week {st['midsem_after_week']}) · **Level:** {st['level']}xx · "
  f"**Department:** {st['department']} · **Lectures:** {len(st['schedule']['weeks'])} × 1.5 h · **Labs:** {len(st['labs_tutorials']['labs'])} × 2 h\n")
a(f"_Design written by hand (not generated by ProfsAgent); checked with ProfsAgent's deterministic validators: 0 errors._\n")
a("## Description\n")
a(c["description"] + "\n")
a(f"**Central question:** {c['central_question']}\n")
ts = c["target_students"]
a(f"**Students:** {ts['year']} ({', '.join(ts['programmes'])}); assumed background: {'; '.join(ts['assumed_background'])}.\n")
a("## Prerequisites and positioning\n")
for p in st["positioning"]["prerequisites"]:
    a(f"- **{p['course_uid']}** ({p['kind']}): relies on {', '.join(p['relied_topics'])}. {p['justification']}")
for x in st["positioning"].get("comparable", []):
    a(f"- **Compared with {x['ref']}:** {x['note']}")
a("")
a("## Course outcomes\n")
a("| CO | Statement | Bloom |")
a("|---|---|---|")
for co in st["cos"]:
    a(f"| {co['id']} | {co['statement']} | {co['bloom_level']} |")
a("\n## Learning outcomes\n")
a("| LO | Statement | Bloom | Taught in |")
a("|---|---|---|---|")
for lo in st["los"]:
    weeks = sorted(week_of[t] for t, (tt, _m) in tmap.items() if lo["id"] in tt["serves_los"])
    a(f"| {lo['id']} | {lo['statement']} | {lo['bloom_level']} | week {', '.join(map(str, weeks))} |")
a("\n## CO–PO mapping (all CSE programmes; 3 = strong, 2 = moderate, 1 = slight)\n")
import re  # noqa: E402
pos = sorted({x["po_uid"] for x in st["copo"]}, key=lambda u: (st["programmes"].index(u.split("/")[0]),
                                                               re.sub(r"\d+", "", u.split("/")[1]), int(re.sub(r"\D", "", u.split("/")[1]))))
a("| Programme outcome | " + " | ".join(co["id"] for co in st["cos"]) + " |")
a("|---|" + "---|" * len(st["cos"]))
cell = {(x["co_id"], x["po_uid"]): x["strength_provisional"] for x in st["copo"]}
for u in pos:
    a(f"| {u} | " + " | ".join(str(cell.get((co['id'], u), '')) for co in st["cos"]) + " |")
a("\n## Weekly plan\n")
a("| Week | Module | Lecture (1.5 h) | LOs | Lab (2 h) | Assessment due |")
a("|---|---|---|---|---|---|")
labs = {l["week"]: l for l in st["labs_tutorials"]["labs"]}
due = {}
for comp in st["assessment"]["components"]:
    for i in comp["instances"]:
        due.setdefault(i["due_week"], []).append(i["id"].split(":", 1)[1])
for w in st["schedule"]["weeks"]:
    t, m = tmap[w["items"][0]["topic_id"]]
    lab = labs.get(w["week"])
    mark = " **(mid-semester exam after this week)**" if w.get("is_midsem_boundary") else ""
    a(f"| {w['week']} | {m['title']} | {t['title']}{mark} | {', '.join(t['serves_los'])} | {lab['title'] if lab else ''} | {', '.join(due.get(w['week'], []))} |")
a("\n## Labs\n")
for l in st["labs_tutorials"]["labs"]:
    a(f"- **Week {l['week']} · {l['title']}.** {l['exercise']} _Tools:_ {', '.join(l['tools'])}. _Practises:_ {', '.join(l['practises_los'])}.")
a(f"\nInfrastructure: {'; '.join(st['labs_tutorials']['infra_requirements'])}.\n")
a("## Assessment\n")
a("| Component | Weight | Instances (release → due week) | LOs assessed |")
a("|---|---|---|---|")
for comp in st["assessment"]["components"]:
    inst = "; ".join(f"{i['id'].split(':', 1)[1]} (w{i['release_week']}→w{i['due_week']})" for i in comp["instances"])
    los = sorted({x["lo_id"] for i in comp["instances"] for x in i["assesses"]})
    a(f"| {comp['type']}{' (proctored)' if comp.get('proctored') else ''} | {comp['weight_pct']:.0f}% | {inst} | {', '.join(los)} |")
a("\n**Team project (30%).** Teams of 3–4 build a small web product with AI assistants across the whole lifecycle, in three "
  "milestones: (1) requirements and design (user stories with acceptance criteria, an architecture decision record); "
  "(2) build and test (every AI-written change reviewed, tests with a mutation-score target); (3) ship, secure and measure "
  "(CI with an AI review step and static analysis, a security audit, timed measurements of AI's effect, and the team's "
  "reflection and AI-use policy).\n")
a("## Reading list\n")
for r in st["resources"]:
    idf = r["identifier"]
    link = f"arXiv:{idf['arxiv']}" if idf.get("arxiv") else (idf.get("url") or "")
    a(f"- **{r['role']}** · {', '.join(r['authors'])} ({r['year']}). *{r['title']}*. {r['venue']}{(', ' + r['edition'] + ' ed.') if r.get('edition') else ''}. {link}")
a("")
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(L), encoding="utf-8")
print("written", out)
